import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

export const OUT = join(import.meta.dir, "..", "workflows", "checkpoint.js");

// The runtime reads the meta literal before it runs the script, so it must stay the first statement.
const META = /^export const meta = \{\n[\s\S]*?\n\};\n/m;
const IMPORT = /^import\s[\s\S]*?\sfrom\s+["'][^"']+["'];?[ \t]*\n/gm;
const EXPORT = /^export\s+(?=(?:async\s+)?(?:function|const|let|type|interface)\b)/gm;
const MODULE_SYNTAX = /^\s*(?:import|export)\s/m;

function transpile(source: string, name: string): string {
  const js = new Bun.Transpiler({ loader: "ts" }).transformSync(source).trim();
  if (MODULE_SYNTAX.test(js)) throw new Error(`${name} still has import or export syntax after the build stripped it.`);
  return js;
}

// Tests import this to check that the committed file matches the sources.
export function buildSource(): string {
  const decide = readFileSync(join(import.meta.dir, "engine", "decide.ts"), "utf8");
  const body = readFileSync(join(import.meta.dir, "workflows", "checkpoint.ts"), "utf8");
  const meta = body.match(META);
  if (!meta) throw new Error("checkpoint.ts must hold `export const meta = {` ... `};` as a pure literal.");
  return [
    meta[0].trimEnd(),
    "// Generated by src/build.ts from src/engine/decide.ts and src/workflows/checkpoint.ts. Do not edit.",
    "",
    transpile(decide.replace(EXPORT, ""), "decide.ts"),
    "",
    transpile(body.replace(META, "").replace(IMPORT, ""), "checkpoint.ts"),
    "",
    // The runtime wraps the script in an async function. A top-level return is not valid
    // module syntax, so the build adds it after the transpile.
    "return main();",
    "",
  ].join("\n");
}

if (import.meta.main) {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, buildSource());
  console.log(`Wrote ${OUT}`);
}
