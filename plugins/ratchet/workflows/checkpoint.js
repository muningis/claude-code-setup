async function run(cfg) {
  const abs = (path) => absPath(cfg.repo, path);
  const evRel = (file) => `${evidenceDir(cfg.slug, cfg.cp)}/${file}`;
  const evAbs = (file) => abs(evRel(file));
  const evDir = abs(evidenceDir(cfg.slug, cfg.cp));
  const pathOrNull = (value) => typeof value === "string" && value !== "" ? abs(value) : null;
  let epoch = cfg.epoch;
  let rounds = { b0: 0, b1: 0, b2: 0, b3: 0 };
  let base = { ...rounds };
  let implRound = 0;
  let nonceCount = 0;
  const concerns = [];
  const evidence = {};
  const lastReview = { arch: null, break: null };
  const stop = (status, summary, question = null) => ({
    stop: true,
    status,
    summary,
    question
  });
  const finish = (status, summary, question = null) => {
    log(`Result: ${status}. ${clip(summary, 200)}`);
    return composeResult({
      status,
      slug: cfg.slug,
      cp: cfg.cp,
      epoch,
      rounds,
      summary,
      question,
      evidence: Object.values(evidence).flat()
    });
  };
  const note = (name, res) => {
    const paths = unique([res.evidence, res.patch].flat().filter((p) => typeof p === "string" && p !== ""));
    if (paths.length > 0)
      evidence[name] = paths;
  };
  const relay = async (label, command, nonce, phaseTitle) => {
    const wrapped = await agent(relayPrompt(cfg, command), {
      agentType: "ratchet:relay",
      schema: RELAY_SCHEMA,
      model: cfg.models.relay || "haiku",
      label,
      phase: phaseTitle
    });
    const parsed = parseRelay(wrapped);
    if (!parsed.ok)
      throw stop("harness-error", `Relay ${label} failed. ${parsed.reason}`);
    const res = parsed.value;
    const check = verifyRelay(res, nonce);
    if (!check.ok)
      throw stop("harness-error", `Relay ${label} failed. ${check.reason}`);
    return res;
  };
  const gate = async (name, round, phaseTitle, opts = {}) => {
    nonceCount += 1;
    const nonce = makeNonce(cfg.nonce, nonceCount);
    const command = gateCommand(cfg.rs, name, cfg.slug, cfg.cp, nonce, round, [...opts.extra || [], "--detach"]);
    let res = await relay(`gate ${name} r${round}`, command, nonce, phaseTitle);
    for (let waits = 0;gateVerdict(res) === "pending"; waits++) {
      if (waits >= MAX_WAITS)
        throw stop("harness-error", `The ${name} gate still runs after ${waits} waits.`);
      if (!isSafeJob(res.job))
        throw stop("harness-error", `The ${name} gate returned a bad job ID.`);
      nonceCount += 1;
      const waitNonce = makeNonce(cfg.nonce, nonceCount);
      res = await relay(`wait ${name} r${round}`, waitCommand(cfg.rs, cfg.slug, cfg.cp, res.job, waitNonce), waitNonce, phaseTitle);
    }
    const verdict = gateVerdict(res);
    log(`${name} round ${round}: ${verdict}. ${clip(res.summary, 120)}`);
    note(name, res);
    if (verdict === "error" && !(opts.tolerate && opts.tolerate(res))) {
      throw stop("harness-error", `The ${name} gate could not run. ${sentence(res.summary)}`);
    }
    return { res, pass: verdict === "pass", error: verdict === "error" };
  };
  const preflight = async () => {
    phase(P.pre);
    nonceCount += 1;
    const stateNonce = makeNonce(cfg.nonce, nonceCount);
    const state = await relay("state", stateCommand(cfg.rs, cfg.slug, cfg.cp, stateNonce), stateNonce, P.pre);
    const check = checkState(state, cfg);
    if (!check.ok)
      throw stop("harness-error", check.reason);
    if (typeof state.epoch === "number")
      epoch = state.epoch;
    rounds = stateRounds(state);
    base = { ...rounds };
    implRound = rounds.b1;
    log(`State: stage ${state.stage}. Rounds so far: b0 ${rounds.b0}, b1 ${rounds.b1}, b2 ${rounds.b2}, b3 ${rounds.b3}.`);
    return state;
  };
  const stageB0 = async () => {
    phase(P.b0);
    const prep = await gate("b0-prep", base.b0 + 1, P.b0);
    if (!prep.pass)
      throw stop("harness-error", `The b0-prep gate did not pass. ${sentence(prep.res.summary)}`);
    let retry = null;
    for (let n = 1;n <= SPEC_ROUNDS; n++) {
      const r = base.b0 + n;
      const spec = await agent(specPrompt(cfg, evDir, r, evAbs("0-spec.json"), retry), agentOpts("ratchet:spec", `spec r${r}`, P.b0, SPEC_SCHEMA, cfg.models.spec));
      if (!spec)
        throw stop("harness-error", "The spec agent returned nothing.");
      const g = await gate("b0", r, P.b0);
      rounds.b0 = r;
      if (g.pass)
        return;
      if (capExhausted(n, SPEC_ROUNDS)) {
        const why = `The spec gate failed after ${n} rounds. ${sentence(g.res.summary)}`;
        throw stop("blocked", why, why);
      }
      retry = { evidence: pathOrNull(g.res.evidence) };
    }
  };
  const buildUntilGreen = async (first, context) => {
    phase(P.b1);
    let fix = first;
    for (let n = 1;n <= cfg.caps.b1; n++) {
      implRound += 1;
      const r = implRound;
      const resumed = n === 1 ? { label: "Brief, if it exists", path: evAbs(`1-brief-r${r}.md`), summary: "" } : null;
      const impl = await agent(implementPrompt(cfg, evDir, r, evAbs("0-spec.json"), evAbs(`1-impl-r${r}.json`), fix || resumed), agentOpts("ratchet:implement", `implement r${r}`, P.b1, IMPLEMENT_SCHEMA, implementModel(r, cfg.models)));
      if (!impl)
        throw stop("harness-error", "The implement agent returned nothing.");
      note("implement", { evidence: evRel(`1-impl-r${r}.json`) });
      const outcome = classifyImplement(impl);
      if (outcome.action === "error") {
        throw stop("harness-error", `The implement agent returned an unknown status: ${clip(impl.status, 40) || "none"}.`);
      }
      if (outcome.action === "decide") {
        throw stop("needs-decision", `The implementer reported ${impl.status} in round ${r}.`, outcome.question);
      }
      concerns.push(...outcome.concerns);
      let failed = null;
      const b1 = await gate("b1", r, P.b1);
      rounds.b1 = r;
      if (!b1.pass)
        failed = { name: "b1", res: b1.res };
      else {
        const smoke = await gate("smoke", r, P.b1);
        if (!smoke.pass)
          failed = { name: "smoke", res: smoke.res };
      }
      if (!failed)
        return;
      if (capExhausted(n, cfg.caps.b1)) {
        const where = context ? ` This happened while fixing the ${context}.` : "";
        throw stop("needs-decision", `The ${failed.name} gate still fails after ${n} rounds.`, capQuestion(failed.name, n, `Last result: ${sentence(failed.res.summary)}${where}`));
      }
      fix = { label: "Brief", path: pathOrNull(failed.res.brief || failed.res.evidence), summary: clip(failed.res.summary, 160) };
    }
  };
  const stageB2 = async () => {
    phase(P.b2);
    for (let n = 1;n <= cfg.caps.b2; n++) {
      const r = base.b2 + n;
      rounds.b2 = r;
      let g = null;
      for (let attempt = 0;attempt <= INVALID_RECAPTURES; attempt++) {
        const capture = await gate("b2-capture", r, P.b2);
        if (capture.pass)
          return;
        const visual = await agent(visualPrompt(cfg, evDir, r, imageLines(cfg.repo, capture.res.images), pathOrNull(capture.res.evidence), evAbs(`2-visual-r${r}.json`)), agentOpts("ratchet:visual", `visual r${r}`, P.b2, VISUAL_SCHEMA, cfg.models.visual));
        if (!visual)
          throw stop("harness-error", "The visual agent returned nothing.");
        g = await gate("b2", r, P.b2, { tolerate: isInvalidCapture, extra: ["--verdict-b64", utf8Base64(JSON.stringify(visual))] });
        if (!g.error)
          break;
        if (attempt === INVALID_RECAPTURES)
          throw stop("harness-error", `The captures stay invalid. ${sentence(g.res.summary)}`);
        log("The captures show different states. Capturing again.");
      }
      if (!g)
        throw stop("harness-error", "The b2 gate did not run.");
      if (g.pass)
        return;
      if (capExhausted(n, cfg.caps.b2)) {
        throw stop("needs-decision", `The b2 gate still finds blocking visual differences after ${n} rounds.`, capQuestion("b2", n, `Last result: ${sentence(g.res.summary)}`));
      }
      await buildUntilGreen({ label: "Findings", path: evAbs(`2-visual-r${r}.json`), summary: clip(g.res.summary, 160) }, "B2 visual findings");
      phase(P.b2);
    }
  };
  const stageB3 = async () => {
    phase(P.b3);
    let openArch = 0;
    for (let n = 1;n <= cfg.caps.b3; n++) {
      const r = base.b3 + n;
      rounds.b3 = r;
      const prep = await gate("b3-prep", r, P.b3);
      if (!prep.pass)
        throw stop("harness-error", `The b3-prep gate did not pass. ${sentence(prep.res.summary)}`);
      const roles = skipArch(r, prep.res.structural, openArch) ? ["break"] : ["arch", "break"];
      if (roles.length === 1)
        log("The delta is not structural. Skipping the arch reviewer.");
      const common = {
        patch: pathOrNull(prep.res.patch),
        delta: r >= 2 ? pathOrNull(prep.res.delta) : null,
        tripwire: pathOrNull(prep.res.tripwire),
        checks: [prep.res.checkOutputs].flat().filter((p) => typeof p === "string" && p !== "").map(abs),
        concerns: clip(concerns.join("; "), 600),
        report: implRound > 0 ? evAbs(`1-impl-r${implRound}.json`) : null
      };
      const outs = await parallel(roles.map((role) => () => agent(reviewPrompt(cfg, evDir, role, r, { ...common, previous: r >= 2 ? evAbs(`3-${role}-r${lastReview[role] ?? r - 1}.json`) : null }, evAbs(`3-${role}-r${r}.json`)), agentOpts(role === "arch" ? "ratchet:review-arch" : "ratchet:review-break", `${role} review r${r}`, P.b3, REVIEW_SCHEMA, role === "arch" ? cfg.models.reviewArch : cfg.models.reviewBreak))));
      roles.forEach((role, i) => {
        if (!outs[i])
          throw stop("harness-error", `The ${role} reviewer returned nothing.`);
        lastReview[role] = r;
      });
      const copies = roles.flatMap((role, i) => [`--${role}-b64`, utf8Base64(JSON.stringify(outs[i]))]);
      const g = await gate("b3", r, P.b3, { extra: [...roles.includes("arch") ? [] : ["--skip-arch"], ...copies] });
      openArch = archBlocking(g.res.blocking);
      if (g.pass)
        return;
      if (capExhausted(n, cfg.caps.b3)) {
        const notAddressed = ids(g.res.notAddressed);
        const open = notAddressed.length > 0 ? notAddressed : ids(g.res.blocking);
        const detail = open.length > 0 ? `Not addressed: ${open.join(", ")}.` : `Last result: ${sentence(g.res.summary)}`;
        throw stop("needs-decision", `The b3 review still has blocking findings after ${n} rounds.`, capQuestion("b3", n, detail));
      }
      await buildUntilGreen({ label: "Findings", path: evAbs(`3-triage-r${r}.json`), summary: clip(g.res.summary, 160) }, "B3 review findings");
      phase(P.b3);
    }
  };
  const runners = {
    B0: stageB0,
    B1: () => buildUntilGreen(null, ""),
    B2: stageB2,
    B3: stageB3
  };
  log(`Checkpoint ${cfg.cp} of plan ${cfg.slug}. Mode: ${cfg.mode || "none"}.`);
  try {
    const state = await preflight();
    const stages = stagesFrom(state.stage, state.visual === true);
    if (stages === null) {
      throw stop("harness-error", `Stage ${clip(state.stage, 20) || "unknown"} is past the engine.`);
    }
    log(`Stages to run: ${stages.length > 0 ? stages.join(", ") : "none"}.`);
    for (const stage of stages)
      await runners[stage]();
    return finish("ready-for-B4", stages.length > 0 ? readySummary(rounds, concerns) : "The checkpoint already passed B3.");
  } catch (e) {
    const err = e;
    if (err && err.stop === true)
      return finish(err.status, err.summary, err.question);
    return finish("harness-error", `The engine stopped on an error. ${sentence(err && err.message ? err.message : err)}`);
  }
}
async function main() {
  const parsed = parseArgs(args);
  if (!parsed.ok) {
    log(`The args are not usable. ${parsed.reason}`);
    return composeResult({
      status: "harness-error",
      slug: null,
      cp: null,
      epoch: null,
      rounds: null,
      summary: `The args are not usable. ${parsed.reason}`
    });
  }
  return run(parsed.config);
}

return main();
